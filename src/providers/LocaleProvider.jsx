const LocaleProvider = ({ children }) => {
  const [locale, setLocale] = useLocalStorage(STORAGE_KEYS.LOCALE, "en")
  const activeLocale = locale === "fr" ? "fr" : "en"

  useEffect(() => {
    document.documentElement.lang = activeLocale
  }, [activeLocale])

  const value = useMemo(
    () => ({
      locale: activeLocale,
      setLocale,
      toggleLocale: () => setLocale((current) => (current === "fr" ? "en" : "fr")),
      t: (message) =>
        activeLocale === "fr"
          ? extraFrenchMessages[message] ?? frenchMessages[message] ?? message
          : message,
    }),
    [activeLocale, setLocale]
  )

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
}

export const useLocale = () => useContext(LocaleContext)

export default LocaleProvider